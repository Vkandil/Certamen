export function t(language: AppLanguage | undefined, key: TranslationKey): string {
  return translations[language ?? 'en'][key] ?? translations.en[key];
}

/** t() with {placeholders} replaced. */
export function tf(language: AppLanguage | undefined, key: TranslationKey, vars: Record<string, string | number>): string {
  return t(language, key).replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

